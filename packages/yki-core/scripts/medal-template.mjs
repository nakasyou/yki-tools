import { readFileSync, writeFileSync } from 'node:fs'

// Keep the attributed OpenSCAD template as the single source of geometry.
const source = readFileSync(
  new URL('../../3d-generator/templates/classical-yo-kai-medal.scad', import.meta.url),
  'utf8',
)
const definitions = /\b(?:code[1-4]|mode)\s*=\s*"(?:[01]*|normal|classic|lite)"\s*;/g
const matches = [...source.matchAll(definitions)]
if (matches.map((match) => match[0].split(' ')[0]).join(',') !== 'code1,code2,code3,code4,mode')
  throw new Error('Unexpected medal template definitions')
const parts = source.split(definitions)
writeFileSync(
  new URL('../medal_template.mbt', import.meta.url),
  '// Generated by scripts/medal-template.mjs from the attributed OpenSCAD template.\n///|\nlet medal_template : Array[String] = [\n' +
    parts.map((part) => `  ${JSON.stringify(part)},`).join('\n') +
    '\n]\n',
)
